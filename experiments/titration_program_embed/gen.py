#!/usr/bin/env python3
"""Regenerate include/default_titration_program.h from a device /api/diagnostics dump.

The embedded program is the firmware's fallback replay for titration-pump calibration
when no measurement has been recorded yet (e.g. a fresh flash). It is a *real* run
captured from the device, reconstructed step-for-step from the diagnostics curve.

Usage:
    # refresh the source dump first:
    curl -s http://khpro.local/api/diagnostics -o khpro_diag_YYYYMMDD.json
    python3 gen.py khpro_diag_YYYYMMDD.json > ../../KHcontroller/Firmware/include/default_titration_program.h

Reconstruction (must mirror src/main.cpp measureKH):
  units : round(Δml * cal_units / titration_vol)         (broadcastTitrationPH inverse)
  mode  : pre-step pH > fast_ph -> fast(0); > GRAN_REGION -> medium(1); else gran(2)
  dwell : fast/medium mix-delay formulas + recorded Gran stabMs  (timing only)
"""
import json
import sys
import statistics

GRAN_REGION = 5.0
FAST_MIX_MS = 200          # TITRATION_MIX_DELAY_FAST_MS
GRAN_FIRST_EXTRA_MS = 5000  # GRAN_FIRST_DOSE_EXTRA_MIX_MS


def reconstruct(d):
    cfg = d["config"]
    calU = cfg["cal_units"]
    titV = cfg["titration_vol"]
    fastPH = cfg["fast_ph"]
    mix = int(cfg["mix_delay"])
    fastBatchMax = max(20, round(cfg["fast_step_ul"] / 1000.0 * calU / titV))
    curve = d["titration_curve"]["points"]  # [ml, pH, mV]
    gran_stab = [p[3] for p in d["analysis_points"]["points"] if p[4] == 2]  # stabMs
    med_stab = int(statistics.median(gran_stab)) if gran_stab else 1500

    prog = []
    prev_ml, prev_pH, gi, first_gran = 0.0, None, 0, True
    for ml, pH, _mV in curve:
        units = round((ml - prev_ml) * calU / titV)
        pre = prev_pH if prev_pH is not None else 99.0
        mode = 0 if pre > fastPH else (1 if pre > GRAN_REGION else 2)
        if mode == 0:
            dwell = FAST_MIX_MS + max(0, fastBatchMax - units) * 600 // fastBatchMax + 300
        elif mode == 1:
            dwell = mix + 1000
        else:
            s = gran_stab[gi] if gi < len(gran_stab) else med_stab
            gi += 1
            dwell = mix + s + (GRAN_FIRST_EXTRA_MS if first_gran else 0)
            first_gran = False
        prog.append((int(units), int(mode), int(min(dwell, 65535))))
        prev_ml, prev_pH = ml, pH
    return prog, cfg


def emit(prog, cfg, d):
    total = sum(p[0] for p in prog)
    body = ",".join(f"{{{u},{m},{dw}}}" for u, m, dw in prog)
    return f"""#ifndef DEFAULT_TITRATION_PROGRAM_H
#define DEFAULT_TITRATION_PROGRAM_H

#include "titration_program.h"

// AUTO-GENERATED by experiments/titration_program_embed/gen.py — do not edit by hand.
// Source: khpro.local /api/diagnostics, device fw_build "{d['fw_build']}", ts={d['timestamp']}.
// Device config at capture: cal_units={cfg['cal_units']}, titration_vol={cfg['titration_vol']},
//   fast_ph={cfg['fast_ph']}, drop_ul={cfg['drop_ul']}, fast_step_ul={cfg['fast_step_ul']}.
//
// A real measurement run embedded as the DEFAULT replay program for titration-pump
// calibration. Used only until the first recorded measurement overwrites
// /history/last_titration.prog. {len(prog)} steps, total {total} units (~{total*cfg['titration_vol']/cfg['cal_units']:.2f} mL).
static const TitrationStep DEFAULT_TITRATION_PROGRAM[] = {{{body}}};
static const int DEFAULT_TITRATION_PROGRAM_LEN =
    sizeof(DEFAULT_TITRATION_PROGRAM) / sizeof(DEFAULT_TITRATION_PROGRAM[0]);

#endif // DEFAULT_TITRATION_PROGRAM_H
"""


if __name__ == "__main__":
    src = sys.argv[1] if len(sys.argv) > 1 else "khpro_diag_20260611.json"
    d = json.load(open(src))
    prog, cfg = reconstruct(d)
    sys.stdout.write(emit(prog, cfg, d))
